#!/usr/bin/env python3
"""Generate and submit SLURM training jobs for ADAF-RTMA from a YAML experiment file.

Ported from the adaf repo's submit_train_adaf*.sh + submit_experiments_from_yaml.sh,
merged into one tool. See docs/SUBMITTING_JOBS.md for the full option reference.

An experiment file is either
  * multi-experiment: `defaults:` + `experiments: {name: {overrides}}` (experiment_configs.yaml), or
  * single-run: a flat mapping of options (configs/train_example.yaml); its name is `name:`
    or the file's stem.

Every key is either a submit option (SUBMIT_KEYS below: SLURM resources, environment,
run directory, resume) or a training option, forwarded to the training script as
`--key value`. Training options are checked against the keys of the experiment's
`config_filepath` YAML, since those are exactly the flags train_ges_goes.py accepts
(utils/misc_functions.set_user_params).

Usage (from the repo root):
  python3 tools/submit_experiments.py experiment_configs.yaml [filter] [--dry-run] [--debug]
                                      [--version V] [--force] [--set key=value ...]
"""
import argparse
import difflib
import os
import re
import shlex
import subprocess
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Consumed here; never forwarded to the training script.
SUBMIT_DEFAULTS = {
    "name": None,              # single-run files only; defaults to the file's stem
    "description": "",
    "script": "train_ges_goes.py",
    # --- SLURM resources ---
    "account": "gpu-emc-ai",
    "partition": "u1-h100",
    "qos": "gpu",
    "nodes": 1,
    "gpus_per_node": 2,
    "cpus_per_task": 24,
    "mem": "0",
    "time": "04:00:00",
    "extra_sbatch": [],        # extra raw "#SBATCH ..." option strings, e.g. ["--exclusive"]
    # --- environment ---
    "env_setup": [],           # shell lines run before training (module load, conda activate, ...)
    "python": "python",        # interpreter after env_setup; its bin dir must also hold ptxas
    "env_vars": {},            # exported into the job, e.g. {OMP_NUM_THREADS: 2}
    "stage_ptxas": True,       # copy ptxas + Triton/Inductor caches to node-local /tmp (for compile_model)
    # --- outputs / resume ---
    "run_dir": "training_runs/{name}",  # logs, job script, checkpoints; {name} = experiment name
    "resume": False,           # resume from resume_checkpoint_path (default: <run_dir>/ckpt.tar)
}
SUBMIT_KEYS = set(SUBMIT_DEFAULTS)
DEBUG_TIME = "00:30:00"

JOB_TEMPLATE = r"""#!/bin/bash -l
# Auto-generated by tools/submit_experiments.py from @@SOURCE@@ (experiment "@@NAME@@").
# Don't edit by hand -- change the YAML and re-run the submitter (--dry-run to preview).
# @@DESCRIPTION@@
#
#SBATCH --account=@@ACCOUNT@@
@@QOS_LINE@@#SBATCH --partition=@@PARTITION@@
#SBATCH -J @@JOB_NAME@@
#SBATCH -o @@RUN_DIR@@/log_%j.out
#SBATCH -e @@RUN_DIR@@/log_%j.err
#SBATCH --nodes=@@NODES@@
#SBATCH --ntasks-per-node=1          # one torchrun launcher per node
#SBATCH --cpus-per-task=@@CPUS@@
#SBATCH --gres=gpu:@@GPUS@@
#SBATCH --mem=@@MEM@@
#SBATCH -t @@TIME@@
#SBATCH --export=ALL
@@EXTRA_SBATCH@@
set -eo pipefail

cd "@@REPO_ROOT@@"
echo "=========================================="
echo "Experiment: @@NAME@@ | Job: $SLURM_JOB_ID | Nodes: $SLURM_JOB_NODELIST"
echo "Started at $(date)"
echo "=========================================="
startTime=$(date +%s)

# === Environment ===
@@ENV_SETUP@@
@@ENV_VARS@@
export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True
export TORCH_NCCL_ASYNC_ERROR_HANDLING=1
PYTHON="$(command -v @@PYTHON@@)"
echo "python: $PYTHON"

# === Rendezvous (shared by all nodes) ===
export MASTER_ADDR=$(scontrol show hostnames "$SLURM_JOB_NODELIST" | head -n 1)
export MASTER_PORT=$((10000 + SLURM_JOB_ID % 20000))
echo "MASTER_ADDR=$MASTER_ADDR MASTER_PORT=$MASTER_PORT NNODES=$SLURM_NNODES"

@@PTXAS_BLOCK@@
# === Launch: one torchrun per node, @@GPUS@@ rank(s) per node (1 per GPU) ===
TRAIN_ARGS=(
@@TRAIN_ARGS@@
)
echo "$PYTHON -m torch.distributed.run ... @@SCRIPT@@ ${TRAIN_ARGS[*]}"
srun --ntasks-per-node=1 --mpi=none --gres=gpu:@@GPUS@@ \
    "$PYTHON" -m torch.distributed.run \
    --nnodes="$SLURM_NNODES" \
    --nproc_per_node=@@GPUS@@ \
    --rdzv_backend=c10d \
    --rdzv_endpoint="$MASTER_ADDR:$MASTER_PORT" \
    --rdzv_id="$SLURM_JOB_ID" \
    "@@SCRIPT@@" "${TRAIN_ARGS[@]}"

echo "runTime=$(( $(date +%s) - startTime ))s"
"""

PTXAS_BLOCK = r"""# === Stage ptxas + Triton/Inductor caches on node-local disk ===
# Exec'ing ptxas off Lustre from many concurrent compile workers gives ETXTBSY.
ENV_BIN="$(dirname "$PYTHON")"
export TRITON_PTXAS_PATH=/tmp/ptxas_${SLURM_JOB_ID}
export TRITON_PTXAS_BLACKWELL_PATH=$TRITON_PTXAS_PATH
export TRITON_CACHE_DIR=/tmp/triton_cache_${SLURM_JOB_ID}
export TORCHINDUCTOR_CACHE_DIR=/tmp/inductor_cache_${SLURM_JOB_ID}
export TORCHINDUCTOR_COMPILE_THREADS=${TORCHINDUCTOR_COMPILE_THREADS:-8}
if [ -x "$ENV_BIN/ptxas" ]; then
    srun --ntasks-per-node=1 --mpi=none bash -c '
      cp -f "'"$ENV_BIN"'/ptxas" "$TRITON_PTXAS_PATH.tmp.$$" &&
      mv -f "$TRITON_PTXAS_PATH.tmp.$$" "$TRITON_PTXAS_PATH" &&
      chmod 755 "$TRITON_PTXAS_PATH" &&
      mkdir -p "$TRITON_CACHE_DIR" "$TORCHINDUCTOR_CACHE_DIR" &&
      echo "$(hostname): staged ptxas -> $TRITON_PTXAS_PATH"'
    trap 'srun --ntasks-per-node=1 --mpi=none rm -rf "$TRITON_PTXAS_PATH" "$TRITON_CACHE_DIR" "$TORCHINDUCTOR_CACHE_DIR" || true' EXIT
else
    echo "WARNING: no ptxas in $ENV_BIN -- not staging (torch.compile may fail or be slow)"
    unset TRITON_PTXAS_PATH TRITON_PTXAS_BLACKWELL_PATH
fi
"""

####################

def load_yaml(path):
    """ruamel (YAML 1.2: 7E-4 is a float) if present, else PyYAML."""
    try:
        from ruamel.yaml import YAML
        with open(path) as f:
            data = YAML(typ="safe", pure=True).load(f)
    except ImportError:
        import yaml
        with open(path) as f:
            data = yaml.safe_load(f)
    return data or {}


def parse_value(text):
    """Value for a --set key=value override, parsed as YAML (so 1, 0.5, true, [4, 4] work)."""
    try:
        from ruamel.yaml import YAML
        return YAML(typ="safe", pure=True).load(text)
    except ImportError:
        import yaml
        return yaml.safe_load(text)


def config_keys(config_filepath):
    """Training flags the config accepts, or None if it can't be read here."""
    try:
        return set((load_yaml(os.path.join(REPO_ROOT, config_filepath)).get("EncDec") or {}).keys())
    except (OSError, ImportError) as e:
        print(f"  warning: can't read {config_filepath} to validate options ({e})", file=sys.stderr)
        return None


def flag_tokens(key, value):
    """--key value tokens as set_user_params parses them."""
    if isinstance(value, bool):
        return [f"--{key}", str(value)]
    if isinstance(value, (list, tuple)):
        return [f"--{key}"] + [str(v) for v in value]
    return [f"--{key}", str(value)]

####################

def resolve_experiments(data, source, filter_str):
    if "experiments" in data:
        defaults = data.get("defaults") or {}
        experiments = {name: {**defaults, **(overrides or {})}
                       for name, overrides in (data.get("experiments") or {}).items()}
    else:  # single-run file
        name = data.get("name") or os.path.splitext(os.path.basename(source))[0]
        experiments = {name: dict(data)}

    if filter_str:
        experiments = {k: v for k, v in experiments.items() if filter_str in k}
    return experiments


def build_job(name, exp, args):
    opts = {**SUBMIT_DEFAULTS, **{k: v for k, v in exp.items() if k in SUBMIT_KEYS}}
    train = {k: v for k, v in exp.items() if k not in SUBMIT_KEYS and v is not None}
    train.setdefault("config_filepath", "./config/params_lowres_ges_goes.yaml")

    run_dir = str(opts["run_dir"]).format(name=name)
    if args.version:
        run_dir = os.path.join(run_dir, args.version)
    run_dir_abs = os.path.join(REPO_ROOT, run_dir)  # join keeps absolute paths as-is

    train.setdefault("checkpoint_path", os.path.join(run_dir, "ckpt.tar"))
    train.setdefault("best_checkpoint_path", os.path.join(run_dir, "best_ckpt.tar"))
    if opts["resume"]:
        train["resuming"] = True
        train.setdefault("resume_checkpoint_path", os.path.join(run_dir, "ckpt.tar"))

    errors = []
    known = config_keys(train["config_filepath"])
    if known is not None:
        for key in train:
            if key != "config_filepath" and key not in known:
                hint = difflib.get_close_matches(key, sorted(known | SUBMIT_KEYS), n=1)
                errors.append(f"unknown option '{key}'" + (f" (did you mean '{hint[0]}'?)" if hint else "")
                              + f" -- not a submit option or a key in {train['config_filepath']}")
    if opts["resume"]:
        resume_from = os.path.join(REPO_ROOT, train["resume_checkpoint_path"])  # join keeps absolute paths as-is
        if not os.path.isfile(resume_from):
            errors.append(f"resume: true but {train['resume_checkpoint_path']} does not exist")
    existing = os.path.join(run_dir_abs, "ckpt.tar")
    if not opts["resume"] and os.path.exists(existing) and not args.force:
        errors.append(f"{existing} exists and would be overwritten -- set resume: true, "
                      "use --version, or pass --force")

    time = DEBUG_TIME if args.debug else opts["time"]
    config_path = train.pop("config_filepath")
    tokens = ["--config_filepath", config_path]
    for key, value in train.items():
        tokens += flag_tokens(key, value)

    def indent_lines(lines):
        return "\n".join(str(line) for line in lines)

    replacements = {
        "SOURCE": args.config_file,
        "NAME": name,
        "DESCRIPTION": str(opts["description"]).replace("\n", " "),
        "ACCOUNT": opts["account"],
        "QOS_LINE": f"#SBATCH --qos={opts['qos']}\n" if opts["qos"] else "",
        "PARTITION": opts["partition"],
        "JOB_NAME": f"adaf_rtma_{name}",
        "RUN_DIR": run_dir_abs,
        "NODES": opts["nodes"],
        "CPUS": opts["cpus_per_task"],
        "GPUS": opts["gpus_per_node"],
        "MEM": opts["mem"],
        "TIME": time,
        "EXTRA_SBATCH": indent_lines(f"#SBATCH {o}" for o in opts["extra_sbatch"]),
        "REPO_ROOT": REPO_ROOT,
        "ENV_SETUP": indent_lines(opts["env_setup"]) or "# (no env_setup given)",
        "ENV_VARS": indent_lines(f"export {k}={shlex.quote(str(v))}" for k, v in opts["env_vars"].items()),
        "PYTHON": opts["python"],
        "PTXAS_BLOCK": PTXAS_BLOCK if opts["stage_ptxas"] else "",
        "SCRIPT": os.path.join(REPO_ROOT, opts["script"]),
        "TRAIN_ARGS": "\n".join(f"    {shlex.quote(t)}" for t in tokens),
    }
    script = JOB_TEMPLATE
    for key, value in replacements.items():
        script = script.replace(f"@@{key}@@", str(value))
    leftover = re.findall(r"@@[A-Z_]+@@", script)
    assert not leftover, f"unfilled template placeholders {leftover}"

    return {"run_dir": run_dir_abs, "script": script, "errors": errors, "opts": opts,
            "time": time, "tokens": tokens}

####################

def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("config_file", nargs="?", default="experiment_configs.yaml",
                        help="experiment YAML ('-' = experiment_configs.yaml)")
    parser.add_argument("filter", nargs="?", default="", help="only experiments whose name contains this")
    parser.add_argument("--dry-run", action="store_true", help="write job scripts, don't submit")
    parser.add_argument("--debug", action="store_true", help=f"override time limit to {DEBUG_TIME}")
    parser.add_argument("--version", default="", help="nest outputs under <run_dir>/<version>")
    parser.add_argument("--force", action="store_true", help="allow overwriting an existing run_dir's ckpt.tar")
    parser.add_argument("--set", action="append", default=[], metavar="KEY=VALUE",
                        help="override an option for every selected experiment (repeatable)")
    args = parser.parse_args()

    if args.config_file == "-":
        args.config_file = "experiment_configs.yaml"
    if not os.path.isfile(args.config_file):
        sys.exit(f"Config file not found: {args.config_file}")

    overrides = {}
    for kv in args.set:
        if "=" not in kv:
            sys.exit(f"--set expects KEY=VALUE, got {kv!r}")
        key, value = kv.split("=", 1)
        overrides[key.strip().lower()] = parse_value(value)

    experiments = resolve_experiments(load_yaml(args.config_file), args.config_file, args.filter)
    if not experiments:
        sys.exit(f"No experiments in {args.config_file}" + (f" matching '{args.filter}'" if args.filter else ""))

    print(f"{len(experiments)} experiment(s) from {args.config_file}"
          + (" [DRY RUN]" if args.dry_run else "") + (" [DEBUG]" if args.debug else ""))
    have_sbatch = subprocess.run(["which", "sbatch"], capture_output=True).returncode == 0 if not args.dry_run else True

    failures = 0
    for i, (name, exp) in enumerate(experiments.items(), 1):
        job = build_job(name, {**exp, **overrides}, args)
        opts = job["opts"]
        print(f"\n[{i}] {name}" + (f" -- {opts['description']}" if opts["description"] else ""))
        print(f"    {opts['nodes']} node(s) x {opts['gpus_per_node']} GPU(s), time {job['time']}, run_dir {job['run_dir']}")
        print(f"    args: {' '.join(shlex.quote(t) for t in job['tokens'])}")
        if job["errors"]:
            failures += 1
            for e in job["errors"]:
                print(f"    ERROR: {e}")
            continue

        os.makedirs(job["run_dir"], exist_ok=True)  # sbatch needs the -o/-e dir to exist
        script_path = os.path.join(job["run_dir"], f"job_{name}.sh")
        with open(script_path, "w", newline="\n") as f:
            f.write(job["script"])
        os.chmod(script_path, 0o755)
        print(f"    job script: {script_path}")

        if args.dry_run:
            print(f"    [dry run] would run: sbatch {script_path}")
        elif not have_sbatch:
            failures += 1
            print("    ERROR: sbatch not found -- run on a login node, or use --dry-run")
        else:
            result = subprocess.run(["sbatch", script_path], cwd=REPO_ROOT, capture_output=True, text=True)
            if result.returncode == 0:
                print(f"    submitted: {result.stdout.strip()}")
            else:
                failures += 1
                print(f"    ERROR: sbatch failed: {result.stderr.strip()}")

    print(f"\n{len(experiments) - failures}/{len(experiments)} experiment(s) "
          + ("prepared" if args.dry_run else "submitted"))
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    main()
